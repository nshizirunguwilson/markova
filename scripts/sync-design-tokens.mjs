#!/usr/bin/env node
/**
 * Generates the platform token files from design/tokens.json.
 *
 *   node scripts/sync-design-tokens.mjs           # write the files
 *   node scripts/sync-design-tokens.mjs --check   # fail if they are stale (CI)
 *
 * Outputs:
 *   web/src/app/tokens.css        - a Tailwind v4 @theme block
 *   mobile/src/design/generated.ts - typeface names and the default brand colour
 *
 * Note the asymmetry. Web takes its whole palette and geometry from here. Mobile
 * takes only the things that must not differ between the two clients: the
 * typeface and the colour a school starts on. Its spacing and radius scales are
 * deliberately its own (see mobile/src/design/tokens.ts) because a phone wants
 * chunkier corners and tighter gutters than a dashboard, and forcing web's
 * numbers onto it would restyle every screen in the app.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

const BANNER = (src) =>
  `/* AUTO-GENERATED by scripts/sync-design-tokens.mjs - DO NOT EDIT.\n` +
  `   Source of truth: design/tokens.json\n` +
  `   Regenerate with: node scripts/sync-design-tokens.mjs */\n`;

/** camelCase -> kebab-case, preserving leading digits (2xl -> 2xl). */
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const colorEntries = Object.entries(tokens.color);
const radiusEntries = Object.entries(tokens.radius).filter(([k]) => !k.startsWith('$'));
const fontSizeEntries = Object.entries(tokens.fontSize).filter(([k]) => !k.startsWith('$'));
const spacingEntries = Object.entries(tokens.spacing).filter(([k]) => !k.startsWith('$'));
const weightEntries = Object.entries(tokens.fontWeight).filter(([k]) => !k.startsWith('$'));
const chartSeries = tokens.chartSeries.values;
const chartCategorical = tokens.chartCategorical.values;
const shadowEntries = Object.entries(tokens.shadow).filter(([k]) => !k.startsWith('$'));

/**
 * Motion, split into the two things it is made of.
 *
 * Durations become `--duration-*` so `duration-quick` reads in a class name;
 * easings become `--ease-*` for `ease-enter`. Both are plain numbers and
 * strings in the token file, so the split is by type rather than by a second
 * nesting level nobody would remember to keep tidy.
 */
const motionEntries = Object.entries(tokens.motion ?? {}).filter(
  ([k]) => !k.startsWith('$'),
);
const durationEntries = motionEntries.filter(([, v]) => typeof v === 'number');
const easingEntries = motionEntries.filter(([, v]) => typeof v === 'string');

// ── web: Tailwind v4 @theme block ───────────────────────────────────────────

/**
 * The colours a school can change at runtime.
 *
 * `@theme inline` bakes each token's value straight into the utilities, so
 * `bg-primary` compiled to a literal hex and re-setting `--color-primary` on
 * the document did nothing - a school could save its brand colour and watch
 * the dashboard stay Markova blue. These are emitted as a plain `:root` block
 * and referenced from the theme, so what gets inlined is `var(--brand-*)` and
 * BrandProvider can repaint the whole app by setting six variables.
 *
 * Everything else stays a literal: it is not brand, and a variable indirection
 * per token costs paint time for nothing.
 */
const RUNTIME_COLORS = [
  'primary',
  'primaryLight',
  'primaryDark',
  'onPrimary',
  'accent',
  'accentLight',
  'info',
  'infoWash',
];

function buildWebCss() {
  const runtime = RUNTIME_COLORS.filter((name) => tokens.color[name]);
  const brandVars = runtime
    .map((name) => `  --brand-${kebab(name)}: ${tokens.color[name].value};`)
    .join('\n');

  const colors = colorEntries
    .map(([name, t]) =>
      runtime.includes(name)
        ? `  --color-${kebab(name)}: var(--brand-${kebab(name)});`
        : `  --color-${kebab(name)}: ${t.value};`,
    )
    .join('\n');

  const radii = radiusEntries
    .map(([name, px]) => `  --radius-${name}: ${px === 9999 ? '9999px' : `${px}px`};`)
    .join('\n');

  const sizes = fontSizeEntries
    .map(([name, px]) => `  --text-${name}: ${px / 16}rem;`)
    .join('\n');

  return `${BANNER()}
/* The school's own colours, overridable at runtime by BrandProvider. */
:root {
${brandVars}
}

@theme inline {
  /* ── colour ─────────────────────────────────────────────────────────────── */
${colors}

  /* ── radius (same pixels as mobile's radius.*) ──────────────────────────── */
${radii}

  /* ── type scale (same pixels as mobile's fontSize.*) ────────────────────── */
${sizes}

  /* ── elevation ──────────────────────────────────────────────────────────── */
${shadowEntries.map(([name, v]) => `  --shadow-${name}: ${v};`).join('\n')}

  /* ── motion (same milliseconds as mobile's duration.*) ──────────────────── */
${durationEntries.map(([name, ms]) => `  --duration-${name}: ${ms}ms;`).join('\n')}
${easingEntries.map(([name, curve]) => `  --ease-${name}: ${curve};`).join('\n')}

  /* ── chart palettes (also exported from web/src/lib/chart-colors.ts) ────── */
${chartSeries.map((c, i) => `  --color-chart-${i + 1}: ${c};`).join('\n')}
${chartCategorical.map((c, i) => `  --color-category-${i + 1}: ${c};`).join('\n')}

  /* ── families ───────────────────────────────────────────────────────────── */
  --font-sans: var(--font-poppins), ${tokens.font.fallback.web};
  --font-mono: ui-monospace, SFMono-Regular, Menlo, monospace;
}
`;
}

// ── mobile: generated design module ─────────────────────────────────────────

/** expo-google-fonts exports one module per weight, named like `Poppins_500Medium`. */
const WEIGHT_LABEL = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold' };

const fontModule = (family, weight) =>
  `${family.replace(/\s+/g, '')}_${weight}${WEIGHT_LABEL[weight]}`;

function buildMobileTs() {
  const sans = tokens.font.family;
  const mono = tokens.font.mono;

  // The sans weights the design system actually asks for. Bundling the rest
  // would cost about a megabyte for weights nothing renders.
  const sansWeights = [400, 500, 600];
  const monoWeights = [400, 500];

  const entry = (family, weight) =>
    `  ${WEIGHT_LABEL[weight].toLowerCase()}: '${fontModule(family, weight)}',`;

  return (
    BANNER() +
    `\n/** The families both clients load. Web via next/font, mobile via expo-font. */\n` +
    `export const fontFamily = {\n` +
    `  sans: '${sans}',\n` +
    `  mono: '${mono}',\n` +
    `} as const;\n` +
    `\n/** Interface type. */\n` +
    `export const sansFont = {\n` +
    sansWeights.map((w) => entry(sans, w)).join('\n') +
    `\n} as const;\n` +
    `\n/** Machine codes only: student IDs, NFC tags, reference numbers. */\n` +
    `export const monoFont = {\n` +
    monoWeights.map((w) => entry(mono, w)).join('\n') +
    `\n} as const;\n` +
    `\n/** What a school is themed with until its own colour loads. */\n` +
    `export const brandDefault = '${tokens.color.primary.value}';\n` +
    `\n/** How long a transition runs, in milliseconds. Same values as the web. */\n` +
    `export const duration = {\n` +
    durationEntries.map(([name, ms]) => `  ${name}: ${ms},`).join('\n') +
    `\n} as const;\n` +
    `\n/** The curves those durations run on, as cubic-bezier control points. */\n` +
    `export const easing = {\n` +
    easingEntries
      .map(([name, curve]) => {
        // Only what is inside the parentheses: matching numbers across the
        // whole string picks up the hyphen in "cubic-bezier" as well.
        const inside = curve.slice(curve.indexOf('(') + 1, curve.lastIndexOf(')'));
        const points = inside.split(',').map((n) => n.trim()).join(', ');
        return `  ${name}: [${points}] as const,`;
      })
      .join('\n') +
    `\n} as const;\n`
  );
}

// ── write / check ───────────────────────────────────────────────────────────

const outputs = [
  ['web/src/app/tokens.css', buildWebCss()],
  ['mobile/src/design/generated.ts', buildMobileTs()],
];

const check = process.argv.includes('--check');
let stale = false;

for (const [rel, content] of outputs) {
  const path = join(root, rel);
  let existing = null;
  try {
    existing = readFileSync(path, 'utf8');
  } catch {
    /* not yet generated */
  }
  if (existing === content) {
    if (!check) console.log(`  unchanged  ${rel}`);
    continue;
  }
  if (check) {
    console.error(`  STALE      ${rel}`);
    stale = true;
  } else {
    writeFileSync(path, content);
    console.log(`  written    ${rel}`);
  }
}

if (check && stale) {
  console.error(
    '\nDesign tokens are out of sync. Run: node scripts/sync-design-tokens.mjs',
  );
  process.exit(1);
}
if (check) console.log('Design tokens are in sync.');
