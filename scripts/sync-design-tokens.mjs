#!/usr/bin/env node
/**
 * Generates the platform token files from design/tokens.json.
 *
 *   node scripts/sync-design-tokens.mjs           # write the files
 *   node scripts/sync-design-tokens.mjs --check   # fail if they are stale (CI)
 *
 * Outputs:
 *   web/src/app/tokens.css        — a Tailwind v4 @theme block
 *   mobile/src/constants/theme.ts — colors / radius / fontSize / fontWeight / spacing
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

const BANNER = (src) =>
  `/* AUTO-GENERATED by scripts/sync-design-tokens.mjs — DO NOT EDIT.\n` +
  `   Source of truth: design/tokens.json\n` +
  `   Regenerate with: node scripts/sync-design-tokens.mjs */\n`;

/** camelCase -> kebab-case, preserving leading digits (2xl -> 2xl). */
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const colorEntries = Object.entries(tokens.color);
const radiusEntries = Object.entries(tokens.radius).filter(([k]) => !k.startsWith('$'));
const fontSizeEntries = Object.entries(tokens.fontSize).filter(([k]) => !k.startsWith('$'));
const spacingEntries = Object.entries(tokens.spacing).filter(([k]) => !k.startsWith('$'));
const weightEntries = Object.entries(tokens.fontWeight).filter(([k]) => !k.startsWith('$'));
const chartSeries = tokens.chartSeries.values;
const chartCategorical = tokens.chartCategorical.values;
const shadowEntries = Object.entries(tokens.shadow).filter(([k]) => !k.startsWith('$'));

// ── web: Tailwind v4 @theme block ───────────────────────────────────────────

function buildWebCss() {
  const colors = colorEntries
    .map(([name, t]) => `  --color-${kebab(name)}: ${t.value};`)
    .join('\n');

  const radii = radiusEntries
    .map(([name, px]) => `  --radius-${name}: ${px === 9999 ? '9999px' : `${px}px`};`)
    .join('\n');

  const sizes = fontSizeEntries
    .map(([name, px]) => `  --text-${name}: ${px / 16}rem;`)
    .join('\n');

  return `${BANNER()}
@theme inline {
  /* ── colour ─────────────────────────────────────────────────────────────── */
${colors}

  /* ── radius (same pixels as mobile's radius.*) ──────────────────────────── */
${radii}

  /* ── type scale (same pixels as mobile's fontSize.*) ────────────────────── */
${sizes}

  /* ── elevation ──────────────────────────────────────────────────────────── */
${shadowEntries.map(([name, v]) => `  --shadow-${name}: ${v};`).join('\n')}

  /* ── chart palettes (also exported from web/src/lib/chart-colors.ts) ────── */
${chartSeries.map((c, i) => `  --color-chart-${i + 1}: ${c};`).join('\n')}
${chartCategorical.map((c, i) => `  --color-category-${i + 1}: ${c};`).join('\n')}

  /* ── families ───────────────────────────────────────────────────────────── */
  --font-sans: var(--font-poppins), ${tokens.font.fallback.web};
  --font-mono: ui-monospace, SFMono-Regular, Menlo, monospace;
}
`;
}

// ── mobile: typed theme module ──────────────────────────────────────────────

function buildMobileTs() {
  const colors = colorEntries
    .map(([name, t]) => `  /** ${t.use} */\n  ${name}: '${t.value}',`)
    .join('\n');

  const radii = radiusEntries
    .map(([name, px]) => `  ${/^\d/.test(name) ? `'${name}'` : name}: ${px},`)
    .join('\n');

  const sizes = fontSizeEntries
    .map(([name, px]) => `  ${/^\d/.test(name) ? `'${name}'` : name}: ${px},`)
    .join('\n');

  const spaces = spacingEntries
    .map(([name, px]) => `  ${/^\d/.test(name) ? `'${name}'` : name}: ${px},`)
    .join('\n');

  const weights = weightEntries
    .map(([name, v]) => `  ${name}: '${v}' as const,`)
    .join('\n');

  const families = tokens.font.weights
    .map((w) => {
      const key = { 400: 'regular', 500: 'medium', 600: 'semibold', 700: 'bold' }[w];
      return `  ${key}: '${tokens.font.family}_${String(w).padStart(3, '0')}${
        { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold' }[w]
      }',`;
    })
    .join('\n');

  return `${BANNER()}
export const colors = {
${colors}
} as const;

export const radius = {
${radii}
} as const;

export const fontSize = {
${sizes}
} as const;

export const spacing = {
${spaces}
} as const;

export const fontWeight = {
${weights}
};

/**
 * expo-font family names. Use \`fontFamily: fontFamily.semibold\` instead of
 * \`fontWeight\` — React Native will not synthesise weights for a custom family.
 */
export const fontFamily = {
${families}
} as const;

/** Sequential brand ramp for single-measure charts. Fills only, not text. */
export const chartSeries = [
${chartSeries.map((c) => `  '${c}',`).join('\n')}
] as const;

/** Distinct hues for unordered categories; each clears 4.5:1 against white. */
export const chartCategorical = [
${chartCategorical.map((c) => `  '${c}',`).join('\n')}
] as const;

export type ThemeColor = keyof typeof colors;
`;
}

// ── write / check ───────────────────────────────────────────────────────────

const outputs = [
  ['web/src/app/tokens.css', buildWebCss()],
  ['mobile/src/constants/theme.ts', buildMobileTs()],
];

const check = process.argv.includes('--check');
let stale = false;

for (const [rel, content] of outputs) {
  const path = join(root, rel);
  let existing = null;
  try {
    existing = readFileSync(path, 'utf8');
  } catch {
    /* not yet generated */
  }
  if (existing === content) {
    if (!check) console.log(`  unchanged  ${rel}`);
    continue;
  }
  if (check) {
    console.error(`  STALE      ${rel}`);
    stale = true;
  } else {
    writeFileSync(path, content);
    console.log(`  written    ${rel}`);
  }
}

if (check && stale) {
  console.error(
    '\nDesign tokens are out of sync. Run: node scripts/sync-design-tokens.mjs',
  );
  process.exit(1);
}
if (check) console.log('Design tokens are in sync.');
