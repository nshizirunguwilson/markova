/**
 * Fills the ID card artwork in.
 *
 * The design lives in `design/id-card-front.svg` and is owned by whoever draws
 * it. This only replaces the contents of elements with the ids listed in
 * docs/STUDENT-ID-CARD.md, so the artwork can be redrawn without touching any
 * code. An id the artwork does not contain is simply skipped, which is how a
 * school that would rather not print the level just deletes that element.
 */

export interface CardData {
  name: string;
  studentIdNumber: string;
  level?: string | null;
  photoUrl?: string | null;
  validUntil?: string | null;
  schoolName?: string | null;
  schoolLogoUrl?: string | null;
  /** A data URI for the QR, generated by the API. */
  qrDataUri?: string | null;
}

/** Initials for the fallback when a student has no photograph on file. */
export function initialsOf(name: string): string {
  return name
    .split(/\s+/)
    .filter(Boolean)
    .slice(0, 2)
    .map((part) => part[0]?.toUpperCase() ?? "")
    .join("");
}

function setText(root: Element, id: string, value: string | null | undefined) {
  const node = root.querySelector(`#${CSS.escape(id)}`);
  if (!node) return;
  if (value === null || value === undefined || value === "") {
    node.remove();
    return;
  }
  node.textContent = value;
}

function setImage(root: Element, id: string, href: string | null | undefined) {
  const node = root.querySelector(`#${CSS.escape(id)}`);
  if (!node) return;
  if (!href) {
    node.remove();
    return;
  }
  // Plain `href`, not the namespaced `xlink:href`: setting the latter without
  // declaring the xlink namespace produces SVG that will not parse again.
  node.setAttribute("href", href);
}

/**
 * Returns the artwork with this student's details in it.
 *
 * `template` is the raw SVG text. The result is SVG text ready to inject or
 * print, so nothing here depends on React.
 */
export function renderIdCard(template: string, data: CardData): string {
  const doc = new DOMParser().parseFromString(template, "image/svg+xml");
  const root = doc.documentElement;
  if (root.nodeName === "parsererror" || root.querySelector("parsererror")) {
    throw new Error("The ID card artwork is not valid SVG");
  }

  setText(root, "student-name", data.name);
  setText(root, "student-id", data.studentIdNumber);
  setText(root, "student-level", data.level ?? null);
  setText(root, "card-validity", data.validUntil ? `Valid to ${data.validUntil}` : null);
  setText(root, "school-name", data.schoolName ?? null);

  setImage(root, "school-logo", data.schoolLogoUrl ?? null);

  // Photo and fallback are mutually exclusive: whichever cannot be used is
  // removed, so a card never shows an empty frame over a set of initials.
  if (data.photoUrl) {
    setImage(root, "student-photo", data.photoUrl);
    root.querySelector("#student-photo-fallback")?.remove();
  } else {
    root.querySelector("#student-photo")?.remove();
    const fallback = root.querySelector("#student-photo-fallback");
    const label = fallback?.querySelector("text");
    if (label) label.textContent = initialsOf(data.name);
  }

  const qrSlot = root.querySelector("#qr-code");
  if (qrSlot) {
    if (data.qrDataUri) {
      const box = qrSlot.querySelector("rect");
      const x = box?.getAttribute("x") ?? "0";
      const y = box?.getAttribute("y") ?? "0";
      const w = box?.getAttribute("width") ?? "180";
      const h = box?.getAttribute("height") ?? "180";
      const img = doc.createElementNS("http://www.w3.org/2000/svg", "image");
      img.setAttribute("x", x);
      img.setAttribute("y", y);
      img.setAttribute("width", w);
      img.setAttribute("height", h);
      img.setAttribute("href", data.qrDataUri);
      qrSlot.replaceWith(img);
    } else {
      // No card issued yet, so there is nothing to scan. An empty box would
      // read as a QR that failed to print.
      qrSlot.remove();
    }
  }

  return new XMLSerializer().serializeToString(root);
}
